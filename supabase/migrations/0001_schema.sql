-- ---------------------------------------------------------------------
-- SETĂRI (un rând per utilizator)
-- ---------------------------------------------------------------------
create table if not exists public.settings (
  user_id               uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  -- preț filament în lei/kg, per material
  pret_filament_lei_kg  jsonb        not null default
    '{"PLA": 100, "PETG": 110, "TPU": 170, "ABS": 110, "ASA": 140, "PLA-CF": 190, "Altul": 120}'::jsonb,
  cost_curent_lei_kwh   numeric(8,4) not null default 1.30 check (cost_curent_lei_kwh >= 0),
  consum_imprimanta_w   numeric(8,2) not null default 100  check (consum_imprimanta_w >= 0),
  ore_de_printare_pe_zi numeric(4,1) not null default 16   check (ore_de_printare_pe_zi > 0 and ore_de_printare_pe_zi <= 24),
  ora_inceput_zi        smallint     not null default 8    check (ora_inceput_zi between 0 and 23),
  -- zile libere din săptămână: 0 = duminică ... 6 = sâmbătă
  zile_libere           smallint[]   not null default '{}',
  -- date libere punctuale (concediu, sărbători)
  date_libere           date[]       not null default '{}',
  adaos_procent         numeric(6,2) not null default 100  check (adaos_procent >= 0),
  updated_at            timestamptz  not null default now()
);

-- ---------------------------------------------------------------------
-- CLIENȚI
-- ---------------------------------------------------------------------
create table if not exists public.clients (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users (id) on delete cascade,
  nume       text not null check (length(trim(nume)) > 0),
  telefon    text,
  email      text,
  oras       text,
  note       text,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- COMENZI
-- Statusuri: noua -> in_coada -> se_printeaza -> finalizata -> livrata (+ anulata)
-- grame_filament și durata_print_ore sunt TOTALE pentru toată comanda.
-- ---------------------------------------------------------------------
create table if not exists public.orders (
  id               bigint generated by default as identity primary key,
  user_id          uuid   not null default auth.uid() references auth.users (id) on delete cascade,
  client_id        bigint references public.clients (id) on delete set null,
  titlu            text   not null check (length(trim(titlu)) > 0),
  descriere        text,
  material         text   not null default 'PLA',
  culoare          text,
  grame_filament   numeric(10,2) not null default 0 check (grame_filament >= 0),
  durata_print_ore numeric(8,2)  not null default 0 check (durata_print_ore >= 0),
  nr_bucati        integer       not null default 1 check (nr_bucati > 0),
  pret_vanzare     numeric(10,2) not null default 0 check (pret_vanzare >= 0),
  cost_material    numeric(10,2) not null default 0, -- calculat automat (trigger)
  status           text   not null default 'noua'
                   check (status in ('noua', 'in_coada', 'se_printeaza', 'finalizata', 'livrata', 'anulata')),
  prioritate       text   not null default 'normala' check (prioritate in ('normala', 'urgenta')),
  data_comanda     date   not null default current_date,
  deadline         date,
  data_start       timestamptz,
  data_finalizare  timestamptz,
  platit           text   not null default 'nu' check (platit in ('da', 'nu', 'partial')), -- calculat din încasări
  suma_incasata    numeric(10,2) not null default 0,                                     -- calculat din încasări
  note             text,
  poza_url         text,      -- calea fișierului în Supabase Storage (bucket „poze-comenzi”)
  pozitie_in_coada integer,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create index if not exists orders_user_status_idx on public.orders (user_id, status);
create index if not exists orders_client_idx      on public.orders (client_id);

-- ---------------------------------------------------------------------
-- ÎNCASĂRI (o comandă poate fi plătită în mai multe tranșe)
-- ---------------------------------------------------------------------
create table if not exists public.payments (
  id         bigint generated by default as identity primary key,
  user_id    uuid   not null default auth.uid() references auth.users (id) on delete cascade,
  order_id   bigint not null references public.orders (id) on delete cascade,
  suma       numeric(10,2) not null check (suma > 0),
  data       date   not null default current_date,
  metoda     text   not null default 'numerar' check (metoda in ('numerar', 'transfer', 'card', 'altul')),
  note       text,
  created_at timestamptz not null default now()
);
create index if not exists payments_order_idx on public.payments (order_id);

-- ---------------------------------------------------------------------
-- ISTORIC COMANDĂ (completat automat de triggere)
-- ---------------------------------------------------------------------
create table if not exists public.order_events (
  id         bigint generated by default as identity primary key,
  user_id    uuid   not null default auth.uid() references auth.users (id) on delete cascade,
  order_id   bigint not null references public.orders (id) on delete cascade,
  tip        text   not null,  -- creata | status | deadline | pret | incasare | incasare_stearsa
  detalii    text,
  created_at timestamptz not null default now()
);
create index if not exists order_events_order_idx on public.order_events (order_id, created_at);

-- =====================================================================
-- FUNCȚII + TRIGGERE
-- =====================================================================

create or replace function public.status_label(s text)
returns text language sql immutable as $$
  select case s
    when 'noua' then 'Nouă'
    when 'in_coada' then 'În coadă'
    when 'se_printeaza' then 'Se printează'
    when 'finalizata' then 'Finalizată'
    when 'livrata' then 'Livrată'
    when 'anulata' then 'Anulată'
    else s end
$$;

-- Cost material = grame / 1000 * preț lei/kg al materialului (sau „Altul” dacă lipsește).
create or replace function public.calc_cost_material(p_user uuid, p_material text, p_grame numeric)
returns numeric language sql stable set search_path = public as $$
  select round(
    coalesce(
      (select coalesce((s.pret_filament_lei_kg ->> p_material)::numeric,
                       (s.pret_filament_lei_kg ->> 'Altul')::numeric)
         from public.settings s where s.user_id = p_user),
      0) * coalesce(p_grame, 0) / 1000.0, 2)
$$;

-- BEFORE INSERT/UPDATE pe comenzi: cost material, date automate, poziție în coadă, status plată.
create or replace function public.orders_before_write()
returns trigger language plpgsql set search_path = public as $$
declare
  status_changed boolean := tg_op = 'INSERT' or new.status is distinct from old.status;
begin
  -- cost material: recalculat când se schimbă grame/material (setările îl actualizează separat)
  if tg_op = 'INSERT'
     or new.grame_filament is distinct from old.grame_filament
     or new.material is distinct from old.material then
    new.cost_material := public.calc_cost_material(new.user_id, new.material, new.grame_filament);
  end if;

  if status_changed then
    -- începe printarea: data_start = acum (dacă nu a fost setată explicit)
    if new.status = 'se_printeaza'
       and (new.data_start is null or (tg_op = 'UPDATE' and new.data_start is not distinct from old.data_start)) then
      new.data_start := now();
      new.data_finalizare := null;
    end if;

    if new.status in ('finalizata', 'livrata') then
      if new.data_finalizare is null then
        new.data_finalizare := now();
      end if;
      if new.data_start is null then
        new.data_start := new.data_finalizare - make_interval(secs => new.durata_print_ore * 3600);
      end if;
    end if;

    -- intră în coadă: se pune la final
    if new.status = 'in_coada' and new.pozitie_in_coada is null then
      select coalesce(max(o.pozitie_in_coada), 0) + 1 into new.pozitie_in_coada
        from public.orders o
       where o.user_id = new.user_id and o.status = 'in_coada';
    end if;
  end if;

  if new.status <> 'in_coada' then
    new.pozitie_in_coada := null;
  end if;

  -- status plată
  new.platit := case
    when new.suma_incasata > 0 and new.suma_incasata >= new.pret_vanzare then 'da'
    when new.suma_incasata > 0 then 'partial'
    else 'nu' end;

  new.updated_at := now();
  return new;
end $$;

drop trigger if exists orders_before_write on public.orders;
create trigger orders_before_write
  before insert or update on public.orders
  for each row execute function public.orders_before_write();

-- AFTER INSERT/UPDATE pe comenzi: istoric.
create or replace function public.orders_after_write()
returns trigger language plpgsql set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    insert into public.order_events (user_id, order_id, tip, detalii)
    values (new.user_id, new.id, 'creata', 'Comandă creată cu statusul ' || public.status_label(new.status));
    return new;
  end if;

  if new.status is distinct from old.status then
    insert into public.order_events (user_id, order_id, tip, detalii)
    values (new.user_id, new.id, 'status', public.status_label(old.status) || ' → ' || public.status_label(new.status));
  end if;

  if new.deadline is distinct from old.deadline then
    insert into public.order_events (user_id, order_id, tip, detalii)
    values (new.user_id, new.id, 'deadline',
            coalesce(to_char(old.deadline, 'DD.MM.YYYY'), '—') || ' → ' || coalesce(to_char(new.deadline, 'DD.MM.YYYY'), '—'));
  end if;

  if new.pret_vanzare is distinct from old.pret_vanzare then
    insert into public.order_events (user_id, order_id, tip, detalii)
    values (new.user_id, new.id, 'pret', old.pret_vanzare || ' → ' || new.pret_vanzare || ' lei');
  end if;

  return new;
end $$;

drop trigger if exists orders_after_write on public.orders;
create trigger orders_after_write
  after insert or update on public.orders
  for each row execute function public.orders_after_write();

-- Încasări: menține orders.suma_incasata (=> platit) + istoric.
create or replace function public.payments_after_write()
returns trigger language plpgsql set search_path = public as $$
declare
  oid bigint := coalesce(new.order_id, old.order_id);
begin
  update public.orders o
     set suma_incasata = coalesce((select sum(p.suma) from public.payments p where p.order_id = o.id), 0)
   where o.id = oid;

  if tg_op = 'UPDATE' and new.order_id is distinct from old.order_id then
    update public.orders o
       set suma_incasata = coalesce((select sum(p.suma) from public.payments p where p.order_id = o.id), 0)
     where o.id = old.order_id;
  end if;

  -- istoric (doar dacă comanda încă există – la ștergerea comenzii, încasările dispar în cascadă)
  if exists (select 1 from public.orders where id = oid) then
    if tg_op = 'INSERT' then
      insert into public.order_events (user_id, order_id, tip, detalii)
      values (new.user_id, new.order_id, 'incasare', 'Încasat ' || new.suma || ' lei (' || new.metoda || ')');
    elsif tg_op = 'DELETE' then
      insert into public.order_events (user_id, order_id, tip, detalii)
      values (old.user_id, old.order_id, 'incasare_stearsa', 'Încasare ștearsă: ' || old.suma || ' lei');
    end if;
  end if;

  return coalesce(new, old);
end $$;

drop trigger if exists payments_after_write on public.payments;
create trigger payments_after_write
  after insert or update or delete on public.payments
  for each row execute function public.payments_after_write();

-- Setări: la schimbarea prețurilor de filament, recalculează costul comenzilor încă neprintate.
create or replace function public.settings_before_update()
returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists settings_before_update on public.settings;
create trigger settings_before_update
  before update on public.settings
  for each row execute function public.settings_before_update();

create or replace function public.settings_after_write()
returns trigger language plpgsql set search_path = public as $$
begin
  if tg_op = 'INSERT' or new.pret_filament_lei_kg is distinct from old.pret_filament_lei_kg then
    update public.orders o
       set cost_material = public.calc_cost_material(o.user_id, o.material, o.grame_filament)
     where o.user_id = new.user_id
       and o.status in ('noua', 'in_coada');
  end if;
  return new;
end $$;

drop trigger if exists settings_after_write on public.settings;
create trigger settings_after_write
  after insert or update on public.settings
  for each row execute function public.settings_after_write();

-- Reordonarea cozii dintr-un singur apel: ids în ordinea dorită.
create or replace function public.reorder_queue(ids bigint[])
returns void language sql set search_path = public as $$
  update public.orders o
     set pozitie_in_coada = t.ord
    from unnest(ids) with ordinality as t(id, ord)
   where o.id = t.id
     and o.user_id = auth.uid()
     and o.status = 'in_coada';
$$;

-- La crearea unui utilizator nou (adminul), creează automat rândul de setări.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.settings (user_id) values (new.id) on conflict (user_id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Pentru utilizatorii existenți deja
insert into public.settings (user_id)
select id from auth.users
on conflict (user_id) do nothing;

