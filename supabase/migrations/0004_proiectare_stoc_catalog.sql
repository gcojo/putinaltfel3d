-- ---------------------------------------------------------------------
-- Cost material pentru o comandă (un material sau mai multe componente)
-- ---------------------------------------------------------------------
create or replace function public.calc_order_cost(p_user uuid, p_material text, p_grame numeric, p_comp jsonb)
returns numeric language sql stable set search_path = public as $$
  select case
    when jsonb_typeof(p_comp) = 'array' and jsonb_array_length(p_comp) > 0 then
      (select coalesce(sum(public.calc_cost_material(p_user, coalesce(c ->> 'material', p_material),
                                                      coalesce((c ->> 'grame')::numeric, 0))), 0)
         from jsonb_array_elements(p_comp) c)
    else public.calc_cost_material(p_user, p_material, p_grame)
  end
$$;

-- aceeași funcție ca în 0001, doar costul ține cont și de componente
create or replace function public.orders_before_write()
returns trigger language plpgsql set search_path = public as $$
declare
  status_changed boolean := tg_op = 'INSERT' or new.status is distinct from old.status;
begin
  if tg_op = 'INSERT'
     or new.grame_filament is distinct from old.grame_filament
     or new.material is distinct from old.material
     or new.componente is distinct from old.componente then
    new.cost_material := public.calc_order_cost(new.user_id, new.material, new.grame_filament, new.componente);
  end if;

  if status_changed then
    if new.status = 'se_printeaza'
       and (new.data_start is null or (tg_op = 'UPDATE' and new.data_start is not distinct from old.data_start)) then
      new.data_start := now();
      new.data_finalizare := null;
    end if;

    if new.status in ('finalizata', 'livrata') then
      if new.data_finalizare is null then
        new.data_finalizare := now();
      end if;
      if new.data_start is null then
        new.data_start := new.data_finalizare - make_interval(secs => new.durata_print_ore * 3600);
      end if;
    end if;

    if new.status = 'in_coada' and new.pozitie_in_coada is null then
      select coalesce(max(o.pozitie_in_coada), 0) + 1 into new.pozitie_in_coada
        from public.orders o
       where o.user_id = new.user_id and o.status = 'in_coada';
    end if;
  end if;

  if new.status <> 'in_coada' then
    new.pozitie_in_coada := null;
  end if;

  new.platit := case
    when new.suma_incasata > 0 and new.suma_incasata >= new.pret_vanzare then 'da'
    when new.suma_incasata > 0 then 'partial'
    else 'nu' end;

  new.updated_at := now();
  return new;
end $$;

create or replace function public.settings_after_write()
returns trigger language plpgsql set search_path = public as $$
begin
  if tg_op = 'INSERT' or new.pret_filament_lei_kg is distinct from old.pret_filament_lei_kg then
    update public.orders o
       set cost_material = public.calc_order_cost(o.user_id, o.material, o.grame_filament, o.componente)
     where o.user_id = new.user_id
       and o.status in ('noua', 'in_coada');
  end if;
  return new;
end $$;

-- ---------------------------------------------------------------------
-- STOC FILAMENT: fiecare rând e o mișcare (+ rolă nouă, − consum comandă, ± corecție).
-- Stocul pentru material + culoare = suma mișcărilor.
-- ---------------------------------------------------------------------
create table if not exists public.filament_moves (
  id         bigint generated by default as identity primary key,
  user_id    uuid   not null default auth.uid() references auth.users (id) on delete cascade,
  material   text   not null,
  culoare    text,
  grame      numeric(10,2) not null,
  tip        text   not null check (tip in ('rola', 'comanda', 'ajustare')),
  order_id   bigint references public.orders (id) on delete set null,
  note       text,
  created_at timestamptz not null default now()
);
create index if not exists filament_moves_user_idx  on public.filament_moves (user_id, material);
create index if not exists filament_moves_order_idx on public.filament_moves (order_id);

-- Comanda finalizată scade filamentul din stoc; dacă revine (ex. „Anulează”), consumul se șterge.
create or replace function public.orders_filament()
returns trigger language plpgsql set search_path = public as $$
declare
  done_new boolean := new.status in ('finalizata', 'livrata');
  done_old boolean := tg_op = 'UPDATE' and old.status in ('finalizata', 'livrata');
begin
  if done_new and not done_old then
    if jsonb_typeof(new.componente) = 'array' and jsonb_array_length(new.componente) > 0 then
      insert into public.filament_moves (user_id, material, culoare, grame, tip, order_id)
      select new.user_id, coalesce(c ->> 'material', new.material), nullif(trim(c ->> 'culoare'), ''),
             -((c ->> 'grame')::numeric), 'comanda', new.id
        from jsonb_array_elements(new.componente) c
       where coalesce((c ->> 'grame')::numeric, 0) > 0;
    elsif new.grame_filament > 0 then
      insert into public.filament_moves (user_id, material, culoare, grame, tip, order_id)
      values (new.user_id, new.material, nullif(trim(new.culoare), ''), -new.grame_filament, 'comanda', new.id);
    end if;
  elsif done_old and not done_new then
    delete from public.filament_moves where order_id = new.id and tip = 'comanda';
  end if;
  return new;
end $$;

drop trigger if exists orders_filament on public.orders;
create trigger orders_filament
  after insert or update of status on public.orders
  for each row execute function public.orders_filament();

-- ---------------------------------------------------------------------
-- CATALOG DE PRODUSE (valori PE BUCATĂ)
-- ---------------------------------------------------------------------
create table if not exists public.products (
  id         bigint generated by default as identity primary key,
  user_id    uuid   not null default auth.uid() references auth.users (id) on delete cascade,
  nume       text   not null check (length(trim(nume)) > 0),
  descriere  text,
  material   text   not null default 'PLA',
  culoare    text,
  componente jsonb,
  grame      numeric(10,2) not null default 0 check (grame >= 0),
  ore        numeric(8,2)  not null default 0 check (ore >= 0),
  pret       numeric(10,2) not null default 0 check (pret >= 0),
  note       text,
  created_at timestamptz not null default now()
);
create index if not exists products_user_idx on public.products (user_id, nume);

