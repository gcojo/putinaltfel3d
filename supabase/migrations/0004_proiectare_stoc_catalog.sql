create policy filament_moves_owner on public.filament_moves for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

drop policy if exists products_owner on public.products;
create policy products_owner on public.products for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

grant select, insert, update, delete on public.filament_moves, public.products to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.calc_order_cost(uuid, text, numeric, jsonb) to authenticated;
revoke all on public.filament_moves, public.products from anon;
